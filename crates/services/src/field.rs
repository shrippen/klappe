/// What a refused value was meant for. Surfaces show it by `name` through the catalogue
/// (`field.<name>`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Field {
    Angle,
    Aspect,
    Camera,
    Character,
    Color,
    Crew,
    Depth,
    Description,
    Distance,
    Drawing,
    Follows,
    Gear,
    Group,
    Height,
    HoldS,
    Kind,
    Lens,
    Movement,
    Name,
    Note,
    Number,
    Pace,
    Point,
    Points,
    Props,
    Sensor,
    SetWidth,
    Short,
    Size,
    Source,
    Tilt,
    Title,
    Wall,
    Width,
}

impl Field {
    pub const ALL: [Field; 34] = [
        Self::Angle,
        Self::Aspect,
        Self::Camera,
        Self::Character,
        Self::Color,
        Self::Crew,
        Self::Depth,
        Self::Description,
        Self::Distance,
        Self::Drawing,
        Self::Follows,
        Self::Gear,
        Self::Group,
        Self::Height,
        Self::HoldS,
        Self::Kind,
        Self::Lens,
        Self::Movement,
        Self::Name,
        Self::Note,
        Self::Number,
        Self::Pace,
        Self::Point,
        Self::Points,
        Self::Props,
        Self::Sensor,
        Self::SetWidth,
        Self::Short,
        Self::Size,
        Self::Source,
        Self::Tilt,
        Self::Title,
        Self::Wall,
        Self::Width,
    ];

    /// The part of the catalogue key behind `field.`.
    pub fn name(self) -> &'static str {
        match self {
            Self::Angle => "angle",
            Self::Aspect => "aspect",
            Self::Camera => "camera",
            Self::Character => "character",
            Self::Color => "color",
            Self::Crew => "crew",
            Self::Depth => "depth",
            Self::Description => "description",
            Self::Distance => "distance",
            Self::Drawing => "drawing",
            Self::Follows => "follows",
            Self::Gear => "gear",
            Self::Group => "group",
            Self::Height => "height",
            Self::HoldS => "hold_s",
            Self::Kind => "kind",
            Self::Lens => "lens",
            Self::Movement => "movement",
            Self::Name => "name",
            Self::Note => "note",
            Self::Number => "number",
            Self::Pace => "pace",
            Self::Point => "point",
            Self::Points => "points",
            Self::Props => "props",
            Self::Sensor => "sensor",
            Self::SetWidth => "set width",
            Self::Short => "short",
            Self::Size => "size",
            Self::Source => "source",
            Self::Tilt => "tilt",
            Self::Title => "title",
            Self::Wall => "wall",
            Self::Width => "width",
        }
    }
}
